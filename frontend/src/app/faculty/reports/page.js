"use client";

import React, { useState } from "react";
import DashboardLayout from "@/components/layout/DashboardLayout";
import PageHeader from "@/components/ui/PageHeader";
import { downloadReport } from "@/lib/api";
import { FileSpreadsheet, Download } from "lucide-react";

export default function FacultyReportsPage() {
  const [downloading, setDownloading] = useState("");

  const handleDownload = async (type, format, endpoint, filename) => {
    setDownloading(`${type}-${format}`);
    try {
      await downloadReport(`${endpoint}?format=${format}`, filename);
    } finally {
      setDownloading("");
    }
  };

  return (
    <DashboardLayout allowedRoles={["faculty", "admin"]}>
      <PageHeader
        title="Faculty Academic Reports & Exports"
        subtitle="Export attendance reports and defaulter lists generated by backend Python services."
      />

      <div className="grid grid-cols-1 md:grid-cols-3 gap-5">
        <div className="bg-white rounded-lg border border-red-200 p-5 shadow-card flex flex-col justify-between bg-red-50/20">
          <div>
            <div className="w-9 h-9 rounded-lg bg-red-100 text-red-800 flex items-center justify-center font-bold mb-3">
              <FileSpreadsheet className="w-5 h-5" />
            </div>
            <h3 className="text-sm font-bold text-gray-900">Official Defaulter Report</h3>
            <p className="text-xs text-gray-600 mt-1 leading-relaxed">
              Export students having attendance below 75% with exact lecture deficit.
            </p>
          </div>
          <div className="pt-4 mt-4 border-t border-gray-100 flex items-center space-x-2">
            <button
              onClick={() => handleDownload("defaulters", "excel", "/reports/defaulters", "Subject_Defaulters.xlsx")}
              className="flex-1 py-1.5 text-xs font-semibold text-emerald-800 bg-emerald-50 hover:bg-emerald-100 border border-emerald-200 rounded text-center"
            >
              Excel (.xlsx)
            </button>
            <button
              onClick={() => handleDownload("defaulters", "csv", "/reports/defaulters", "Subject_Defaulters.csv")}
              className="flex-1 py-1.5 text-xs font-semibold text-blue-800 bg-blue-50 hover:bg-blue-100 border border-blue-200 rounded text-center"
            >
              CSV (.csv)
            </button>
          </div>
        </div>

        <div className="bg-white rounded-lg border border-border p-5 shadow-card flex flex-col justify-between">
          <div>
            <div className="w-9 h-9 rounded-lg bg-primary-light text-primary flex items-center justify-center font-bold mb-3">
              <FileSpreadsheet className="w-5 h-5" />
            </div>
            <h3 className="text-sm font-bold text-gray-900">Subject-wise Attendance</h3>
            <p className="text-xs text-gray-600 mt-1 leading-relaxed">
              Comprehensive report of attendance percentages across enrolled students.
            </p>
          </div>
          <div className="pt-4 mt-4 border-t border-gray-100 flex items-center space-x-2">
            <button
              onClick={() => handleDownload("subject", "excel", "/reports/subject", "Subject_Attendance.xlsx")}
              className="flex-1 py-1.5 text-xs font-semibold text-emerald-800 bg-emerald-50 hover:bg-emerald-100 border border-emerald-200 rounded text-center"
            >
              Excel (.xlsx)
            </button>
            <button
              onClick={() => handleDownload("subject", "csv", "/reports/subject", "Subject_Attendance.csv")}
              className="flex-1 py-1.5 text-xs font-semibold text-blue-800 bg-blue-50 hover:bg-blue-100 border border-blue-200 rounded text-center"
            >
              CSV (.csv)
            </button>
          </div>
        </div>

        <div className="bg-white rounded-lg border border-border p-5 shadow-card flex flex-col justify-between">
          <div>
            <div className="w-9 h-9 rounded-lg bg-primary-light text-primary flex items-center justify-center font-bold mb-3">
              <FileSpreadsheet className="w-5 h-5" />
            </div>
            <h3 className="text-sm font-bold text-gray-900">Date-wise Attendance Log</h3>
            <p className="text-xs text-gray-600 mt-1 leading-relaxed">
              Session-by-session detailed attendance sheets with timestamps and remarks.
            </p>
          </div>
          <div className="pt-4 mt-4 border-t border-gray-100 flex items-center space-x-2">
            <button
              onClick={() => handleDownload("date", "excel", "/reports/date-wise", "Date_Wise_Attendance.xlsx")}
              className="flex-1 py-1.5 text-xs font-semibold text-emerald-800 bg-emerald-50 hover:bg-emerald-100 border border-emerald-200 rounded text-center"
            >
              Excel (.xlsx)
            </button>
            <button
              onClick={() => handleDownload("date", "csv", "/reports/date-wise", "Date_Wise_Attendance.csv")}
              className="flex-1 py-1.5 text-xs font-semibold text-blue-800 bg-blue-50 hover:bg-blue-100 border border-blue-200 rounded text-center"
            >
              CSV (.csv)
            </button>
          </div>
        </div>
      </div>
    </DashboardLayout>
  );
}
